CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE, hash text NOT NULL, name text NOT NULL,
  role text NOT NULL DEFAULT 'customer' CHECK (role IN ('customer','staff','admin')),
  finance integer NOT NULL DEFAULT 0 CHECK (finance IN (0,1)),
  profile text NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS sessions (
  token text PRIMARY KEY, owner text NOT NULL, user_id integer REFERENCES users(id),
  expires bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS orders (
  ref text PRIMARY KEY, owner text NOT NULL, user_id integer REFERENCES users(id),
  idem text NOT NULL, kind text NOT NULL, status text NOT NULL, total integer NOT NULL,
  payload text NOT NULL, created text NOT NULL, UNIQUE(owner,idem)
);
CREATE INDEX IF NOT EXISTS orders_user_time ON orders(user_id,created DESC);
CREATE INDEX IF NOT EXISTS orders_owner_time ON orders(owner,created DESC);
CREATE TABLE IF NOT EXISTS oidc_requests (
  state text PRIMARY KEY, session text NOT NULL, verifier text NOT NULL,
  nonce text NOT NULL, expires bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS identities (
  issuer text NOT NULL, subject text NOT NULL, user_id integer NOT NULL REFERENCES users(id),
  PRIMARY KEY(issuer,subject)
);
